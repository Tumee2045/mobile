/**
 * Copies the platform-neutral code from ../front-end into this app, so web and
 * mobile share one source of truth (types, mock API + demo data, HTTP client,
 * helpers). Edit those files in front-end, then run `npm run sync:shared`.
 * Mobile-specific files (src/api/mode.ts, src/api/index.ts) are NOT synced.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const web = resolve(root, '../front-end/src');

const FILES = [
  'api/types.ts',
  'api/useApi.ts',
  'api/mock/server.ts',
  'api/mock/db.ts',
  'api/mock/reliability.ts',
  'api/http/client.ts',
  'lib/format.ts',
  'auth/permissions.ts',
];

const HEADER = '// GENERATED by scripts/sync-shared.mjs from front-end/src — edit the front-end copy, not this one.\n';

for (const file of FILES) {
  const src = readFileSync(resolve(web, file), 'utf8');
  const dest = resolve(root, 'src/shared', file);
  mkdirSync(dirname(dest), { recursive: true });
  writeFileSync(dest, HEADER + src);
  console.log('synced', file);
}
